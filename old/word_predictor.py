def predict_next_tokens(text, model, sp, max_len=48, top_k=5):
    model.eval()

    ids = sp.encode(text, out_type=int)
    ids = [sp.bos_id()] + ids
    ids = ids[-(max_len - 1):]   # keep recent context only

    x = torch.tensor([ids], dtype=torch.long, device=DEVICE)

    with torch.no_grad():
        logits = model(x)                     # [1, T, V]
        next_logits = logits[0, -1]          # [V]
        probs = F.softmax(next_logits, dim=-1)
        top_probs, top_ids = torch.topk(probs, k=top_k)

    results = []
    for prob, idx in zip(top_probs.tolist(), top_ids.tolist()):
        piece = sp.id_to_piece(idx)
        decoded = sp.decode([idx]) if idx not in [sp.bos_id(), sp.eos_id(), sp.pad_id(), sp.unk_id()] else piece
        results.append({
            "id": idx,
            "piece": piece,
            "decoded": decoded,
            "prob": prob
        })

    return results


