def is_good_text(text: str) -> bool:
    text = clean_text(text)

    if not text:
        return False

    # too short
    if len(text) < 5:
        return False

    # remove obvious junk
    bad_patterns = [
        r"http[s]?://",
        r"www\.",
        r"<[^>]+>",
    ]
    for pat in bad_patterns:
        if re.search(pat, text):
            return False

    # require enough Devanagari characters
    dev_chars = re.findall(r"[\u0900-\u097F]", text)
    if len(dev_chars) < 3:
        return False

    return True

