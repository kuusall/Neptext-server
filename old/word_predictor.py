def encode_texts(texts, sp, max_len):
    encoded = []

    for t in texts:
        ids = sp.encode(t, out_type=int)

        # add BOS and EOS
        ids = [sp.bos_id()] + ids + [sp.eos_id()]

        # truncate
        ids = ids[:max_len]

        # pad
        if len(ids) < max_len:
            ids = ids + [sp.pad_id()] * (max_len - len(ids))

        encoded.append(ids)

    return encoded

